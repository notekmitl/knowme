  /// Correct only a proven cross-area source binding. Keep the selected theme,
  /// legacy pool and all raw report/evidence data unchanged. No word matching.
  static String thaiDashboard(ThaiMirrorLifeDashboardItemState item) {
    final source = item.currentStateSource;
    final text =
        source != null &&
            source.text == item.currentState &&
            source.requestedAspect != source.sourceAspect
        ? source.matchingAspectText
        : item.currentState;
    return thai(text);
  }

