def _planets_in_house(planets: dict, house: int) -> list[str]:
    return [
        planet
        for planet, data in planets.items()
        if data.get("house") == house and planet in PLANET_TH
    ]


def _relevant_house(planets: dict, houses: tuple[int, ...]) -> tuple[int, list[str]] | None:
    for house in houses:
        matches = _planets_in_house(planets, house)
        if matches:
            return house, matches
    return None


def _closest_aspect(
    aspects: list[dict],
    planets: set[str],
    kinds: set[str] | None = None,
) -> dict | None:
    for aspect in aspects:
        if kinds is not None and aspect.get("aspect") not in kinds:
            continue
        if aspect.get("planet1") in planets or aspect.get("planet2") in planets:
            return aspect
    return None


