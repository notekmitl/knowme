def _basis_big3(sun: str, moon: str, rising: str) -> str:
    return f"ดวงอาทิตย์ราศี{_sign(sun)} · ดวงจันทร์ราศี{_sign(moon)} · ลัคนาราศี{_sign(rising)}"


def _basis_work(
    mercury_sign: str,
    mars_sign: str,
    work_house: tuple[int, list[str]] | None,
) -> str:
    basis = f"ดาวพุธราศี{_sign(mercury_sign)} · ดาวอังคารราศี{_sign(mars_sign)}"
    if work_house is None:
        return basis
    house, planets = work_house
    return f"{basis} · {_join_planets(planets)}ในเรือน {house}"


def _basis_money(venus_sign: str, money_house: tuple[int, list[str]] | None) -> str:
    basis = f"ดาวศุกร์ราศี{_sign(venus_sign)}"
    if money_house is None:
        return f"{basis} · ไม่มีดาวหลักในเรือน 2 หรือเรือน 8"
    house, planets = money_house
    return f"{basis} · {_join_planets(planets)}ในเรือน {house}"


def _basis_love(venus_sign: str, moon: str, aspect: dict | None) -> str:
    basis = f"ดาวศุกร์ราศี{_sign(venus_sign)} · ดวงจันทร์ราศี{_sign(moon)}"
    return f"{basis}{_basis_aspect(aspect)}"


def _basis_wellbeing(
    moon: str, dominant_element: str, routine_planets: list[str]
) -> str:
    basis = f"ดวงจันทร์ราศี{_sign(moon)} · {ELEMENT_TH[dominant_element]}"
    if routine_planets:
        return f"{basis} · {_join_planets(routine_planets)}ในเรือน 6"
    return basis


def _basis_caution(dominant_element: str, aspect: dict | None) -> str:
    return f"{ELEMENT_TH[dominant_element]}{_basis_aspect(aspect)}"


def _basis_aspect(aspect: dict | None) -> str:
    if aspect is None:
        return ""
    first = PLANET_TH.get(aspect.get("planet1"), str(aspect.get("planet1")))
    second = PLANET_TH.get(aspect.get("planet2"), str(aspect.get("planet2")))
    label = {
        "conjunction": "กุมกัน",
        "sextile": "ทำมุม 60°",
        "square": "ทำมุม 90°",
        "trine": "ทำมุม 120°",
        "opposition": "ทำมุม 180°",
    }.get(aspect.get("aspect"), str(aspect.get("aspect")))
    return f" · {first}{label}{second}"


def _join_planets(planets: list[str]) -> str:
    names = [PLANET_TH.get(planet, planet) for planet in planets]
    if len(names) <= 1:
        return names[0] if names else "ดาวหลัก"
    return " และ".join(names)


def _sign(value) -> str:
    return SIGN_TH.get(value, str(value or "—"))
