def _relationship_aspect_effect(aspect: dict | None) -> str:
    if aspect is None:
        return "เมื่อพูดความต้องการตรง ๆ ความใกล้ชิดกับพื้นที่ส่วนตัวจะอยู่ร่วมกันได้ง่ายขึ้น"
    kind = aspect.get("aspect")
    if kind in {"square", "opposition"}:
        return "บางครั้งคุณอาจอยากใกล้ชิด แต่อีกจังหวะกลับอยากเว้นระยะ จึงควรบอกให้อีกฝ่ายรู้ว่าเวลานั้นต้องการอะไร"
    if kind in {"trine", "sextile"}:
        return "เวลาต้องการการดูแล คุณมักบอกออกมาและตอบรับอีกฝ่ายด้วยการกระทำ จึงลดโอกาสเข้าใจผิด"
    return "คุณมักแสดงความรู้สึกผ่านสิ่งที่ทำทันที จึงควรบอกด้วยว่าคุณต้องการให้อีกฝ่ายตอบอย่างไร"


