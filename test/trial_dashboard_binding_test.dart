// Independent oracle: reviewed fields of the existing ThemeLifeHints registry
// at 6261951, not text generated by the repaired display function.
const _bCards = {
  'การงาน': 'งานที่ต้องวิเคราะห์และตัดสินใจจากข้อมูลเหมาะกับคุณ',
  'การเงิน': 'คุณลงทุนกับอนาคตมากกว่าความสะดวกในระยะสั้น',
  'ความรัก': 'ความรักมั่นคงเมื่อทั้งสองฝ่ายช่วยกันแก้ปัญหาในชีวิตจริง',
  'สุขภาพ': 'รักษาจังหวะชีวิตสม่ำเสมอจะช่วยให้คุณแข็งแรงต่อเนื่อง',
};

void main() {
  test(
    'source snapshots and all variant pools equal the pre-repair revision',
    () {
      final actual = <String, Object?>{
        'variantPools': {
          for (final theme in ThaiMirrorThemeLifeHints.hints.keys)
            theme: {
              for (final aspect in ['work', 'money', 'love', 'health', 'luck'])
                aspect: ThaiMirrorThemeVariants.aspectHintVariants(
                  theme,
                  aspect,
                ),
            },
        },
      };
      for (final (id, year, month, day, hour, minute, province, key) in [
        ('a', 2001, 1, 15, 12, 34, 'กรุงเทพมหานคร', 'bangkok'),
        ('b', 1990, 5, 12, 8, 15, 'เชียงใหม่', 'chiang mai'),
        ('unknown', 2001, 1, 15, -1, 0, 'กรุงเทพมหานคร', 'bangkok'),
      ]) {
        final analysis = ThaiBetaAnalysisRunner.run(
          ThaiBetaInput(
            firstName: 'QA',
            lastName: 'Synthetic',
            birthDate: DateTime(year, month, day),
            birthHour: hour < 0 ? null : hour,
            birthMinute: minute,
            birthTimeUnknown: hour < 0,
            province: province,
            provinceKey: key,
            gender: 'หญิง',
          ),
          startedAt: DateTime.parse('2026-11-10T03:00:00Z'),
          asOf: DateTime.parse('2026-11-10T03:00:00Z'),
        );
        actual[id] = {
          'snapshot': analysis.reportSnapshot,
          'hash': analysis.reportHash,
          'dashboard': [
            for (final item in analysis.consumerViewState!.lifeDashboard)
              {
                'label': item.label,
                'currentState': item.currentState,
                'whyItAppears': item.whyItAppears,
                'action': item.suggestedAction,
                'status': item.status.name,
              },
          ],
        };
        const domains = {
          'การงาน': 'work',
          'การเงิน': 'money',
          'ความรัก': 'love',
          'สุขภาพ': 'health',
          'โชคและโอกาส': 'luck',
        };
        for (final item in analysis.consumerViewState!.lifeDashboard) {
          final source = item.currentStateSource!;
          expect(source.requestedAspect, domains[item.label]);
          expect(source.text, item.currentState);
          expect(source.themeId, isNotEmpty);
          if (source.sourceAspect == source.requestedAspect) {
            expect(
              TrialReadingCopy.thaiDashboard(item),
              TrialReadingCopy.thai(item.currentState),
            );
          }
        }
        if (id == 'a') {
          final r2 = jsonDecode(
            File(
              'docs/qa/pr149-plain-thai/assembled-reading-review.json',
            ).readAsStringSync(),
          );
          expect(
            analysis.consumerViewState!.lifeDashboard
                .map(TrialReadingCopy.thaiDashboard)
                .toList(),
            (r2['a']['dashboard'] as List).map((e) => e['after']).toList(),
          );
        }
        if (id == 'b') {
          expect(
            analysis.consumerViewState!.lifeDashboard
                .map((i) => i.currentStateSource!.themeId)
                .toList(),
            ['analytical', 'visionary', 'practical', 'stable', 'persistence'],
          );
          expect(
            TrialReadingCopy.thaiDashboard(
              analysis.consumerViewState!.lifeDashboard.last,
            ),
            'โอกาสดีมักมาหลังความพยายามต่อเนื่อง (ผ่านอดทน)',
          );
        }
        if (id == 'unknown')
          expect(analysis.consumerViewState!.lifeDashboard, isEmpty);
      }
      final baseline = File(
        'test/fixtures/trial_readability/dashboard-before-6261951.json',
      );
      expect(actual, jsonDecode(baseline.readAsStringSync()));
    },
  );

  test(
    'duplicate-phrase fallback retains provenance of the actually selected entry',
    () {
      for (final theme in ThaiMirrorThemeLifeHints.hints.keys) {
        for (final aspect in ['work', 'money', 'love', 'health', 'luck']) {
          final parts = ThaiMirrorConsumerCopy.lifeAspectDashboardParts(
            aspect: aspect,
            priorityThemeIds: [theme],
            allThemeIds: [theme],
            profileSeed: 7,
            usedCurrentStates: ThaiMirrorThemeVariants.aspectHintVariants(
              theme,
              aspect,
            ).toSet(),
          );
          expect(parts.currentStateSource!.text, parts.currentState);
          expect(parts.currentStateSource!.requestedAspect, aspect);
          expect(parts.currentStateSource!.themeId, theme);
        }
      }
    },
  );

  test('every theme and all five areas carry the actual field provenance', () {
    for (final theme in ThaiMirrorThemeLifeHints.hints.keys) {
      final life = ThaiMirrorThemeLifeHints.hints[theme]!;
      final fields = {
        'work': life.work,
        'money': life.money,
        'love': life.love,
        'health': life.health,
        'luck': life.luck,
      };
      for (final aspect in fields.keys) {
        for (final source in ThaiMirrorThemeVariants.aspectHintSources(
          theme,
          aspect,
        )) {
          expect(source.themeId, theme);
          expect(source.requestedAspect, aspect);
          if (source.sourceField.startsWith('ThaiMirrorThemeLifeHints.')) {
            expect(
              source.sourceField,
              'ThaiMirrorThemeLifeHints.$theme.${source.sourceAspect}',
            );
            expect(source.text, contains(fields[source.sourceAspect]!));
            expect(
              source.matchingSourceField,
              'ThaiMirrorThemeLifeHints.$theme.$aspect',
            );
            expect(source.matchingAspectText, contains(fields[aspect]!));
          }
        }
      }
    }
  });

  testWidgets(
    'fixture B renders the same-theme source in each correct domain',
    (tester) async {
      final analysis = ThaiBetaAnalysisRunner.run(
        ThaiBetaInput(
          firstName: 'QA',
          lastName: 'Synthetic',
          birthDate: DateTime(1990, 5, 12),
          birthHour: 8,
          birthMinute: 15,
          province: 'เชียงใหม่',
          provinceKey: 'chiang mai',
          gender: 'หญิง',
        ),
        startedAt: DateTime.parse('2026-11-10T03:00:00Z'),
        asOf: DateTime.parse('2026-11-10T03:00:00Z'),
      );
      await tester.binding.setSurfaceSize(const Size(1280, 800));
      addTearDown(() => tester.binding.setSurfaceSize(null));
      await tester.pumpWidget(
        MaterialApp(
          home: ThaiBetaReportPage(
            analysis: analysis,
            anonymousTrial: true,
            audienceOverride: const ThaiBetaEvidenceBadgeAudience.anonymous(),
          ),
        ),
      );
      await tester.pumpAndSettle();
      final actual = <String, String>{};
      for (final label in _bCards.keys) {
        final card = find.byKey(Key('trial-thai-life-$label'));
        actual[label] = tester
            .widgetList<Text>(
              find.descendant(of: card, matching: find.byType(Text)),
            )
            .map((text) => text.data ?? '')
            .join('\n');
      }
      // One aggregate failure captures all four wrong bindings before the fix.
      expect(
        {
          for (final e in _bCards.entries)
            e.key: actual[e.key]!.contains(e.value),
        },
        {for (final label in _bCards.keys) label: true},
        reason: actual.toString(),
      );
    },
  );
}
